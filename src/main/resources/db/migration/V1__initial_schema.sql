CREATE TABLE friendship (
                            friendship_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            requester_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                            recipient_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                            status VARCHAR(20) NOT NULL,
                            CONSTRAINT chk_friendship_order CHECK (requester_id <> recipient_id),
                            CONSTRAINT chk_friendship_status CHECK (status IN ('PENDING', 'ACCEPTED'))
);

CREATE UNIQUE INDEX uk_friendship_pair
    ON friendship (requester_id, recipient_id);

