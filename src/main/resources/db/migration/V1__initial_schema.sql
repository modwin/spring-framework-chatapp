CREATE TABLE chat (
    chat_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL REFERENCES users(user_id)
);

CREATE TABLE chat_users (
    chat_id INTEGER NOT NULL REFERENCES chat(chat_id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    PRIMARY KEY (chat_id, user_id)
);

CREATE TABLE message (
    message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id INTEGER NOT NULL REFERENCES chat(chat_id) ON DELETE CASCADE,
    sender_user_id INTEGER NOT NULL REFERENCES users(user_id),
    content VARCHAR(4000) NOT NULL,
    sent_at TIMESTAMP NOT NULL,
    last_edit TIMESTAMP
);

CREATE INDEX idx_message_chat_sent_at ON message (chat_id, sent_at);
